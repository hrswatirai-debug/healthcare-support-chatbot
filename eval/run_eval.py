"""Evaluation harness for the healthcare support chatbot.

Runs a labeled dataset through the real pipeline and reports the capstone
metrics: intent-classification accuracy, routing accuracy, SQL answer accuracy,
RAG retrieval precision, fallback correctness, and latency.

Usage:
    python eval/run_eval.py                 # offline mock provider (free, deterministic)
    LLM_PROVIDER=openai python eval/run_eval.py   # measure with your real model

Notes on interpretation:
  * Intent, routing, SQL and fallback are deterministic (rules + templated SQL),
    so those numbers are meaningful in either mode.
  * RAG "retrieval precision" (did the correct source document get retrieved) is
    also deterministic (TF-IDF). The *quality* of the generated wording is only
    exercised with a real LLM provider.
"""
from __future__ import annotations

import json
import os
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
os.environ.setdefault("LLM_PROVIDER", "mock")
os.environ.setdefault("DB_PATH", "/tmp/eval_app.db")

from src import db, rag_engine, intent as intent_mod, router  # noqa: E402
import config  # noqa: E402


def _pct(n: int, d: int) -> str:
    return f"{(100.0 * n / d):.1f}%" if d else "n/a"


def load_cases():
    data = json.loads((ROOT / "eval" / "eval_dataset.json").read_text())
    return data["cases"]


def run():
    db.init_db()
    rag_engine.build_index()
    cases = load_cases()

    results = []
    latencies = []
    for c in cases:
        user = {"client_id": c["client_id"], "email": "eval@test.local"}
        pred_intent, _ = intent_mod.classify(c["message"])
        pred_route = intent_mod.route_for(pred_intent, c["message"])

        t0 = time.perf_counter()
        resp = router.handle_message(c["message"], user)
        latency_ms = (time.perf_counter() - t0) * 1000
        latencies.append(latency_ms)

        intent_ok = pred_intent == c["expect_intent"]
        route_ok = pred_route == c["expect_route"]

        task_ok = None
        if c["category"] == "sql":
            task_ok = (resp.data_source == "SQL" and resp.answered
                       and all(s in resp.text for s in c.get("expect_contains", [])))
        elif c["category"] == "rag":
            task_ok = (c.get("expect_source") in (resp.sources or [])) and resp.answered
        elif c["category"] == "fallback":
            task_ok = (not resp.answered) and resp.data_source == "FALLBACK"

        results.append({
            "id": c["id"], "category": c["category"], "intent_ok": intent_ok,
            "route_ok": route_ok, "task_ok": task_ok, "pred_intent": pred_intent,
            "pred_route": pred_route, "data_source": resp.data_source,
            "answered": resp.answered, "latency_ms": latency_ms,
        })

    return results, latencies


def summarize(results, latencies):
    n = len(results)
    intent_ok = sum(r["intent_ok"] for r in results)
    route_ok = sum(r["route_ok"] for r in results)

    by_cat = {}
    for cat in ("sql", "rag", "fallback"):
        subset = [r for r in results if r["category"] == cat]
        ok = sum(1 for r in subset if r["task_ok"])
        by_cat[cat] = (ok, len(subset))

    latencies_sorted = sorted(latencies)
    p95 = latencies_sorted[int(0.95 * (len(latencies_sorted) - 1))]
    avg = sum(latencies) / len(latencies)

    return {
        "n": n,
        "intent": (intent_ok, n),
        "route": (route_ok, n),
        "sql": by_cat["sql"],
        "rag": by_cat["rag"],
        "fallback": by_cat["fallback"],
        "avg_ms": avg,
        "p95_ms": p95,
    }


REPORT_TEMPLATE = """# Evaluation Report

Provider: `{provider}` · Cases: {n} · Generated by `eval/run_eval.py`

| Metric | Capstone target | Result | Pass |
|---|---|---|---|
| Intent classification accuracy | 90%+ | {intent} | {intent_pass} |
| Routing accuracy (SQL vs RAG vs fallback) | — | {route} | — |
| SQL answer accuracy | 95%+ | {sql} | {sql_pass} |
| RAG retrieval precision | 90%+ | {rag} | {rag_pass} |
| Fallback correctness (says "I don't know") | — | {fallback} | — |
| Avg latency (offline pipeline overhead) | < 2000 ms | {avg_ms:.1f} ms | {lat_pass} |
| p95 latency | < 2000 ms | {p95_ms:.1f} ms | {p95_pass} |

*Intent, routing, SQL, and fallback are deterministic (rules + templated
queries) and hold in any provider mode. RAG retrieval precision measures whether
the correct source document was retrieved (TF-IDF, deterministic); answer wording
quality is exercised only with a real LLM provider. Latency here is pipeline
overhead in offline mode — add one LLM round-trip (~1–2s) per RAG answer when
using a real model.*

## Per-case detail

| Case | Category | Intent ✓ | Route ✓ | Task ✓ | source | latency |
|---|---|:--:|:--:|:--:|---|---|
{rows}
"""


def write_report(results, s, provider):
    def mark(ok):
        return "✅" if ok else "❌"

    rows = "\n".join(
        f"| {r['id']} | {r['category']} | {mark(r['intent_ok'])} | "
        f"{mark(r['route_ok'])} | {mark(r['task_ok'])} | {r['data_source']} | "
        f"{r['latency_ms']:.0f} ms |"
        for r in results
    )

    intent_pct = 100.0 * s["intent"][0] / s["intent"][1]
    sql_pct = 100.0 * s["sql"][0] / s["sql"][1] if s["sql"][1] else 0
    rag_pct = 100.0 * s["rag"][0] / s["rag"][1] if s["rag"][1] else 0

    report = REPORT_TEMPLATE.format(
        provider=provider, n=s["n"],
        intent=f"{s['intent'][0]}/{s['intent'][1]} ({_pct(*s['intent'])})",
        route=f"{s['route'][0]}/{s['route'][1]} ({_pct(*s['route'])})",
        sql=f"{s['sql'][0]}/{s['sql'][1]} ({_pct(*s['sql'])})",
        rag=f"{s['rag'][0]}/{s['rag'][1]} ({_pct(*s['rag'])})",
        fallback=f"{s['fallback'][0]}/{s['fallback'][1]} ({_pct(*s['fallback'])})",
        avg_ms=s["avg_ms"], p95_ms=s["p95_ms"],
        intent_pass=mark(intent_pct >= 90),
        sql_pass=mark(sql_pct >= 95),
        rag_pass=mark(rag_pct >= 90),
        lat_pass=mark(s["avg_ms"] < 2000),
        p95_pass=mark(s["p95_ms"] < 2000),
        rows=rows,
    )
    out = ROOT / "eval" / "EVAL_REPORT.md"
    out.write_text(report)
    return out


def main():
    results, latencies = run()
    s = summarize(results, latencies)
    provider = config.resolve_provider()

    print(f"\n=== Evaluation ({provider}) — {s['n']} cases ===")
    print(f"Intent accuracy      : {s['intent'][0]}/{s['intent'][1]}  ({_pct(*s['intent'])})   target 90%+")
    print(f"Routing accuracy     : {s['route'][0]}/{s['route'][1]}  ({_pct(*s['route'])})")
    print(f"SQL answer accuracy  : {s['sql'][0]}/{s['sql'][1]}  ({_pct(*s['sql'])})   target 95%+")
    print(f"RAG retrieval prec.  : {s['rag'][0]}/{s['rag'][1]}  ({_pct(*s['rag'])})   target 90%+")
    print(f"Fallback correctness : {s['fallback'][0]}/{s['fallback'][1]}  ({_pct(*s['fallback'])})")
    print(f"Latency avg / p95    : {s['avg_ms']:.1f} ms / {s['p95_ms']:.1f} ms   target < 2000 ms")

    out = write_report(results, s, provider)
    print(f"\nReport written to {out.relative_to(ROOT)}")

    # Non-zero exit if any hard target missed (useful for CI).
    intent_pct = 100.0 * s["intent"][0] / s["intent"][1]
    sql_pct = 100.0 * s["sql"][0] / s["sql"][1] if s["sql"][1] else 0
    rag_pct = 100.0 * s["rag"][0] / s["rag"][1] if s["rag"][1] else 0
    ok = intent_pct >= 90 and sql_pct >= 95 and rag_pct >= 90
    for r in results:
        if not (r["intent_ok"] and r["route_ok"] and r["task_ok"]):
            print(f"  MISS {r['id']}: intent={r['pred_intent']} route={r['pred_route']} "
                  f"source={r['data_source']} answered={r['answered']}")
    sys.exit(0 if ok else 1)


if __name__ == "__main__":
    main()
